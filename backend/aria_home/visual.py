"""Synthetic visual evidence from SAM 3.1 segmentation.

Provenance: the four images under ``backend/fixtures/visual/`` and the six
care-story frames under ``backend/fixtures/visual/care/`` are SYNTHETIC,
generated by muse-image-1.0; each ``*.sam.txt`` is the recorded raw sam-3.1
response for that image and phrase. Tests replay these recordings; they never
call the network. A scenario ``visual.json`` is one spec (``image_id``,
``phrase``, ``observed_at``, ``received_at``, ``file``) or, for
``care_home_v1``, a list of timed specs; replay visibility is always the
latest spec with ``received_at <= now``.

Policy (enforced in ``readiness.py``, documented in
``docs/readiness-rules.md``): visual evidence never yields ``on_track``,
``warming_observed``, ``goal_verified`` or ``arrival_met``. A water/frost
detection plus a low or unknown indoor temperature can support ``at_risk``
with a citing reason; zero objects is "no detection", never an all-clear.
The running app is replay-only: it never constructs ``SamLiveProvider``
and never sends images anywhere; notification payloads may carry only the
observation line. ``SamLiveProvider`` below is an unintegrated reference
adapter — kept for documentation, constructed nowhere in the app — and it
would POST image bytes to the model API if anyone ever wired it in, so
"images are never sent anywhere" describes the replay-only app, not that
adapter.
"""

import json
import os
import re
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

SAM_MODEL_ID = "sam-3.1"
SAM_BASE_URL = "https://api.meta.ai"
SAM_RESPONSES_PATH = "/v1/responses"
IMAGE_GENERATOR = "muse-image-1.0"
VISUAL_LIVE_ENV = "ARIA_HOME_VISUAL_LIVE"
VISUAL_MODEL_ENV = "ARIA_HOME_VISUAL_MODEL_ID"
VISUAL_URL_ENV = "ARIA_HOME_VISUAL_URL"
MODEL_API_KEY_ENV = "MODEL_API_KEY"
DEFAULT_TIMEOUT_S = 20.0

FIXTURES_DIR = Path(__file__).resolve().parent.parent / "fixtures" / "visual"

BOX_RE = re.compile(
    r"(?:<0f>|\|>,)(\d+)<\|box;x1=(\d+);y1=(\d+);x2=(\d+);y2=(\d+);w=(\d+);h=(\d+)\|>"
)

DETECTION_LABELS = {"water puddle": "water", "frost": "frost"}
SUPPORTED_DETECTIONS = frozenset(DETECTION_LABELS.values())


def detection_label(phrase):
    return DETECTION_LABELS.get(str(phrase or "").strip().lower(), str(phrase or "").strip())


def observation_line(phrase):
    return f"visual observation: {detection_label(phrase)} detected (synthetic image)"


def no_detection_line(phrase):
    return (
        f"visual observation: no detection for {detection_label(phrase)}"
        " (synthetic image); absence of a detection is not an all-clear"
    )


@dataclass(frozen=True)
class SamBox:
    index: int
    x1: int
    y1: int
    x2: int
    y2: int
    image_width: int
    image_height: int

    @property
    def area_fraction(self):
        area = (self.x2 - self.x1) * (self.y2 - self.y1)
        total = self.image_width * self.image_height
        return area / total if total else 0.0

    def as_dict(self):
        return {
            "index": self.index,
            "x1": self.x1,
            "y1": self.y1,
            "x2": self.x2,
            "y2": self.y2,
            "image_width": self.image_width,
            "image_height": self.image_height,
            "area_fraction": self.area_fraction,
        }


def parse_sam_text(text):
    boxes = []
    for match in BOX_RE.finditer(text or ""):
        index, x1, y1, x2, y2, width, height = (int(group) for group in match.groups())
        boxes.append(SamBox(index, x1, y1, x2, y2, width, height))
    return boxes


def extract_sam_text(response):
    if isinstance(response, str):
        try:
            response = json.loads(response)
        except ValueError:
            return ""
    if not isinstance(response, dict):
        return ""
    parts = []
    for message in response.get("output") or []:
        if not isinstance(message, dict):
            continue
        if message.get("type") in ("reasoning", "thinking", "redacted_thinking"):
            continue
        for block in message.get("content") or []:
            if not isinstance(block, dict):
                continue
            if block.get("type") in ("reasoning", "thinking", "redacted_thinking", "reasoning_content"):
                continue
            if block.get("type") not in ("text", "output_text"):
                continue
            if isinstance(block.get("text"), str):
                parts.append(block["text"])
    return "".join(parts)


def largest_box_fraction(boxes):
    return max((box.area_fraction for box in boxes), default=0.0)


def _iso(value):
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value)


@dataclass(frozen=True)
class VisualObservation:
    image_id: str
    file: str | None
    phrase: str
    object_count: int
    largest_box_fraction: float
    boxes: tuple
    image_synthetic: bool
    generator: str
    model: str
    provider_mode: str
    observed_at: str
    received_at: str

    def as_dict(self):
        return {
            "image_id": self.image_id,
            "file": self.file,
            "phrase": self.phrase,
            "object_count": self.object_count,
            "largest_box_fraction": self.largest_box_fraction,
            "boxes": [box.as_dict() for box in self.boxes],
            "image_synthetic": self.image_synthetic,
            "generator": self.generator,
            "model": self.model,
            "provider_mode": self.provider_mode,
            "observed_at": self.observed_at,
            "received_at": self.received_at,
        }


def _observation_from_text(image_id, phrase, text, *, provider_mode, observed_at, received_at, file=None):
    boxes = parse_sam_text(text)
    return VisualObservation(
        image_id=image_id,
        file=file,
        phrase=phrase,
        object_count=len(boxes),
        largest_box_fraction=largest_box_fraction(boxes),
        boxes=tuple(boxes),
        image_synthetic=True,
        generator=IMAGE_GENERATOR,
        model=SAM_MODEL_ID,
        provider_mode=provider_mode,
        observed_at=_iso(observed_at),
        received_at=_iso(received_at),
    )


class ReplayVisualProvider:
    mode = "replay"

    def __init__(self, fixtures_dir=None):
        self.fixtures_dir = Path(fixtures_dir) if fixtures_dir is not None else FIXTURES_DIR

    def recording_path(self, image_id):
        return self.fixtures_dir / f"{image_id}.sam.txt"

    def observe(self, image_id, phrase, *, observed_at, received_at, file=None):
        raw = self.recording_path(image_id).read_text(encoding="utf-8")
        return _observation_from_text(
            image_id,
            phrase,
            extract_sam_text(raw),
            provider_mode=self.mode,
            observed_at=observed_at,
            received_at=received_at,
            file=file,
        )


@dataclass(frozen=True)
class VisualConfig:
    base_url: str | None = SAM_BASE_URL
    model_id: str | None = SAM_MODEL_ID
    api_key: str | None = None
    enabled: bool = False
    timeout_s: float = DEFAULT_TIMEOUT_S

    @property
    def configured(self):
        return bool(self.enabled and self.base_url and self.model_id and self.api_key)

    @classmethod
    def from_env(cls, env=None):
        source = os.environ if env is None else env
        get = source.get if hasattr(source, "get") else lambda k, d=None: getattr(source, k, d)
        base_url = (get(VISUAL_URL_ENV) or SAM_BASE_URL).strip() or SAM_BASE_URL
        model_id = (get(VISUAL_MODEL_ENV) or SAM_MODEL_ID).strip() or SAM_MODEL_ID
        if model_id != SAM_MODEL_ID:
            raise ValueError(f"disallowed visual model id: {model_id!r}; allowed: [{SAM_MODEL_ID!r}]")
        api_key = (get(MODEL_API_KEY_ENV) or "").strip() or None
        raw_enabled = get(VISUAL_LIVE_ENV, False)
        enabled = raw_enabled == "1" or raw_enabled is True
        return cls(base_url=base_url, model_id=model_id, api_key=api_key, enabled=enabled)


def _default_http_post(url, headers, body, timeout_s):
    import httpx

    response = httpx.post(url, headers=headers, json=body, timeout=timeout_s)
    try:
        data = response.json()
    except ValueError:
        data = {}
    return response.status_code, data if isinstance(data, dict) else {}


class SamLiveProvider:
    """Live sam-3.1 segmentation.

    The synthetic scenarios never use it: their visual evidence is
    replay-only (see ``ReplayVisualProvider``). Its one caller is the
    owner-only Nest snapshot route (``POST /api/camera/snapshot`` with
    ``{"segment": true}``, absent in public-demo mode), which uploads that
    one real frame and says so in its response and UI.
    """
    def __init__(self, config=None):
        self.config = config if isinstance(config, VisualConfig) else VisualConfig.from_env(config)
        self.mode = "live" if self.config.enabled else "disabled"

    def build_request(self, image_bytes, phrase, mime="image/webp"):
        import base64

        encoded = base64.b64encode(bytes(image_bytes)).decode("ascii")
        return {
            "url": f"{(self.config.base_url or '').rstrip('/')}{SAM_RESPONSES_PATH}",
            "headers": {
                "Authorization": "Bearer " + (self.config.api_key or ""),
                "Content-Type": "application/json",
            },
            "body": {
                "model": self.config.model_id,
                "input": [
                    {
                        "role": "user",
                        "content": [
                            {"type": "input_text", "text": str(phrase)},
                            {"type": "input_image", "image_url": f"data:{mime};base64,{encoded}"},
                        ],
                    }
                ],
                "metadata": {"mask_encoding": "one_bit"},
            },
        }

    def segment(self, image_bytes, phrase, *, http_post=None, mime="image/webp"):
        if not self.config.configured:
            raise RuntimeError(
                "visual live segmentation refused; set "
                f"{VISUAL_LIVE_ENV}=1 and {MODEL_API_KEY_ENV} to opt in"
            )
        request = self.build_request(image_bytes, phrase, mime=mime)
        sender = http_post or (lambda url, headers, body: _default_http_post(url, headers, body, self.config.timeout_s))
        status, data = sender(request["url"], request["headers"], request["body"])
        if status not in (200, 201):
            raise RuntimeError(f"visual live segmentation failed: http {status}")
        return data

    def observe(self, image_bytes, phrase, image_id, *, observed_at, received_at, file=None, http_post=None):
        data = self.segment(image_bytes, phrase, http_post=http_post)
        return _observation_from_text(
            image_id,
            phrase,
            extract_sam_text(data),
            provider_mode="live",
            observed_at=observed_at,
            received_at=received_at,
            file=file,
        )
